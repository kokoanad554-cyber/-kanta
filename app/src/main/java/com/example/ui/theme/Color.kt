fun paletteColorScheme(palette: AppColorPalette, darkTheme: Boolean): ColorScheme =
    when (palette) {
        AppColorPalette.DESERT_GOLD -> if (darkTheme) DesertDarkColorScheme else DesertLightColorScheme
        AppColorPalette.DEEP_INDIGO -> if (darkTheme) IndigoDarkColorScheme else IndigoLightColorScheme
