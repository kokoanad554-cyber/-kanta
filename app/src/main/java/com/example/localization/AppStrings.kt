    fun sortLabel(option: SortOption): String = when (option) {
        SortOption.NAME_ASC -> sortNameAsc
        SortOption.NAME_DESC -> sortNameDesc
        SortOption.SIZE_DESC -> sortSizeDesc
        SortOption.DATE_DESC -> sortDateDesc
        SortOption.TYPE -> sortType
    }

    fun themeLabel(mode: ThemeMode): String = when (mode) {
        ThemeMode.DARK -> themeDark
        ThemeMode.LIGHT -> themeLight
        ThemeMode.SYSTEM -> themeSystem
    }

    fun paletteLabel(palette: AppColorPalette): String = when (palette) {
        AppColorPalette.DESERT_GOLD -> paletteDesert
        AppColorPalette.DEEP_INDIGO -> paletteIndigo
        AppColorPalette.EMERALD_SLATE -> paletteEmerald
        AppColorPalette.CRIMSON_OBSIDIAN -> paletteCrimson
    }

    fun fontScaleLabel(option: FontScaleOption): String = when (option) {
        FontScaleOption.SMALL -> fontSmall
        FontScaleOption.MEDIUM -> fontMedium
        FontScaleOption.LARGE -> fontLarge
        FontScaleOption.EXTRA_LARGE -> fontExtraLarge
    }

    fun densityLabel(density: ListDensity): String = when (density) {
        ListDensity.COMFORTABLE -> densityComfortable
        ListDensity.COMPACT -> densityCompact
    }

    fun scopeLabel(scope: ScanScope): String = when (scope) {
        ScanScope.ALL_INTERNAL -> scopeAllInternal
        ScanScope.DOWNLOADS -> scopeDownloads
        ScanScope.DOCUMENTS -> scopeDocuments
    }

    fun opTitle(opType: FileOpType): String = when (opType) {
        FileOpType.COPY -> opCopy
        FileOpType.MOVE -> opMove
        FileOpType.DELETE -> opDelete
        FileOpType.COMPRESS -> opCompress
        FileOpType.EXTRACT -> opExtract
