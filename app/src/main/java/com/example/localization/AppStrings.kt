    fun categoryLabel(category: FileCategory): String = when (category) {
        FileCategory.FOLDER -> catFolder
        FileCategory.APK -> catApk
        FileCategory.ARCHIVE -> catArchive
        FileCategory.HTML -> catHtml
        FileCategory.TEXT -> catText
        FileCategory.CODE -> catCode
        FileCategory.PDF -> catPdf
        FileCategory.IMAGE -> catImage
        FileCategory.AUDIO -> catAudio
        FileCategory.VIDEO -> catVideo
        FileCategory.OTHER -> catOther
    }

    fun formatBytes(bytes: Long): String {
        if (bytes <= 0L) return "0 ${byteUnits[0]}"
        val digitGroups = (log10(bytes.toDouble()) / log10(1024.0)).toInt().coerceIn(0, byteUnits.lastIndex)
        val value = bytes / 1024.0.pow(digitGroups.toDouble())
        val formatted = if (digitGroups == 0) bytes.toString() else String.format(Locale.US, "%.1f", value)
        return "$formatted ${byteUnits[digitGroups]}"
    }
